const mongoose = require('mongoose');

const projectSchema = new mongoose.Schema({
  name: {
    type: String,
    required: [true, 'Project name is required'],
    trim: true,
    maxlength: [100, 'Project name cannot exceed 100 characters']
  },
  description: {
    type: String,
    required: [true, 'Project description is required'],
    maxlength: [1000, 'Description cannot exceed 1000 characters']
  },
  owner: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  collaborators: [{
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User'
    },
    role: {
      type: String,
      enum: ['viewer', 'editor', 'admin'],
      default: 'viewer'
    },
    addedAt: {
      type: Date,
      default: Date.now
    }
  }],
  status: {
    type: String,
    enum: ['planning', 'in_progress', 'testing', 'deployed', 'archived'],
    default: 'planning'
  },
  priority: {
    type: String,
    enum: ['low', 'medium', 'high', 'urgent'],
    default: 'medium'
  },
  category: {
    type: String,
    enum: ['web_app', 'mobile_app', 'api', 'desktop_app', 'game', 'other'],
    default: 'web_app'
  },
  technology: {
    frontend: {
      framework: {
        type: String,
        enum: ['react', 'vue', 'angular', 'svelte', 'vanilla'],
        default: 'react'
      },
      styling: {
        type: String,
        enum: ['css', 'scss', 'tailwind', 'styled-components', 'material-ui'],
        default: 'tailwind'
      },
      language: {
        type: String,
        enum: ['javascript', 'typescript'],
        default: 'typescript'
      }
    },
    backend: {
      framework: {
        type: String,
        enum: ['express', 'fastify', 'koa', 'nestjs', 'django', 'flask', 'spring'],
        default: 'express'
      },
      language: {
        type: String,
        enum: ['javascript', 'typescript', 'python', 'java', 'go', 'rust'],
        default: 'javascript'
      },
      runtime: {
        type: String,
        enum: ['nodejs', 'python', 'java', 'go', 'rust'],
        default: 'nodejs'
      }
    },
    database: {
      type: {
        type: String,
        enum: ['mongodb', 'postgresql', 'mysql', 'sqlite', 'redis'],
        default: 'mongodb'
      },
      orm: {
        type: String,
        enum: ['mongoose', 'prisma', 'typeorm', 'sequelize', 'none'],
        default: 'mongoose'
      }
    },
    deployment: {
      platform: {
        type: String,
        enum: ['vercel', 'netlify', 'heroku', 'aws', 'gcp', 'azure', 'docker'],
        default: 'vercel'
      },
      containerized: {
        type: Boolean,
        default: false
      }
    }
  },
  features: [{
    name: {
      type: String,
      required: true
    },
    description: {
      type: String,
      required: true
    },
    status: {
      type: String,
      enum: ['pending', 'in_progress', 'completed', 'testing'],
      default: 'pending'
    },
    priority: {
      type: String,
      enum: ['low', 'medium', 'high'],
      default: 'medium'
    },
    estimatedHours: {
      type: Number,
      default: 0
    },
    actualHours: {
      type: Number,
      default: 0
    },
    assignedTo: {
      type: String, // AI agent type
      enum: ['frontend_agent', 'backend_agent', 'database_agent', 'auth_agent', 'deploy_agent'],
      default: 'frontend_agent'
    },
    createdAt: {
      type: Date,
      default: Date.now
    },
    completedAt: {
      type: Date,
      default: null
    }
  }],
  repository: {
    url: {
      type: String,
      default: null
    },
    branch: {
      type: String,
      default: 'main'
    },
    lastCommit: {
      type: String,
      default: null
    },
    lastSync: {
      type: Date,
      default: null
    }
  },
  deployment: {
    status: {
      type: String,
      enum: ['not_deployed', 'deploying', 'deployed', 'failed'],
      default: 'not_deployed'
    },
    url: {
      type: String,
      default: null
    },
    lastDeployment: {
      type: Date,
      default: null
    },
    deploymentLogs: [{
      timestamp: {
        type: Date,
        default: Date.now
      },
      status: {
        type: String,
        enum: ['started', 'success', 'failed']
      },
      message: {
        type: String
      },
      details: {
        type: mongoose.Schema.Types.Mixed
      }
    }]
  },
  aiGenerated: {
    codeGenerated: {
      type: Number,
      default: 0 // Percentage of code generated by AI
    },
    lastAiInteraction: {
      type: Date,
      default: null
    },
    aiSuggestions: [{
      type: {
        type: String,
        enum: ['optimization', 'feature', 'bug_fix', 'security']
      },
      message: {
        type: String
      },
      implemented: {
        type: Boolean,
        default: false
      },
      createdAt: {
        type: Date,
        default: Date.now
      }
    }]
  },
  settings: {
    autoDeployment: {
      type: Boolean,
      default: false
    },
    aiAssistance: {
      type: Boolean,
      default: true
    },
    codeReview: {
      type: Boolean,
      default: true
    },
    notifications: {
      type: Boolean,
      default: true
    }
  },
  isPublic: {
    type: Boolean,
    default: false
  },
  isArchived: {
    type: Boolean,
    default: false
  },
  tags: [{
    type: String,
    trim: true
  }]
}, {
  timestamps: true,
  toJSON: { virtuals: true },
  toObject: { virtuals: true }
});

// Virtual for completion percentage
projectSchema.virtual('completionPercentage').get(function() {
  if (this.features.length === 0) return 0;
  const completedFeatures = this.features.filter(feature => feature.status === 'completed').length;
  return Math.round((completedFeatures / this.features.length) * 100);
});

// Virtual for total estimated hours
projectSchema.virtual('totalEstimatedHours').get(function() {
  return this.features.reduce((total, feature) => total + (feature.estimatedHours || 0), 0);
});

// Virtual for total actual hours
projectSchema.virtual('totalActualHours').get(function() {
  return this.features.reduce((total, feature) => total + (feature.actualHours || 0), 0);
});

// Pre-save middleware
projectSchema.pre('save', function(next) {
  // Update status based on features completion
  if (this.features.length > 0) {
    const completedFeatures = this.features.filter(f => f.status === 'completed').length;
    const totalFeatures = this.features.length;
    
    if (completedFeatures === 0) {
      this.status = 'planning';
    } else if (completedFeatures === totalFeatures) {
      this.status = 'testing';
    } else {
      this.status = 'in_progress';
    }
  }
  
  next();
});

// Static method to find projects by user
projectSchema.statics.findByUser = function(userId, includeCollaborations = true) {
  const query = includeCollaborations 
    ? { $or: [{ owner: userId }, { 'collaborators.user': userId }] }
    : { owner: userId };
    
  return this.find(query)
    .populate('owner', 'username email firstName lastName avatar')
    .populate('collaborators.user', 'username email firstName lastName avatar')
    .sort({ updatedAt: -1 });
};

// Indexes for better query performance
projectSchema.index({ owner: 1 });
projectSchema.index({ 'collaborators.user': 1 });
projectSchema.index({ status: 1 });
projectSchema.index({ createdAt: -1 });
projectSchema.index({ tags: 1 });
projectSchema.index({ category: 1 });

module.exports = mongoose.model('Project', projectSchema);